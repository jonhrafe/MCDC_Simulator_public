#!/usr/bin/env python3
"""
Geometry validation: the <bounding_box> auto-voxel + intra/extra volume fraction.

The ``<bounding_box>`` flag makes the simulator auto-compute the voxel (and the
walker sampling area) from the obstacle extents instead of a hand-written
``<voxels>`` block. Two things are validated here, on the two meshes generated by
``tests/tools/make_meshes.py``:

(a) CONVEX shell (icosphere, ``bbox_convex.conf``).
    * The auto-computed voxel equals the mesh AABB. We parse the "Min/Max limits"
      the simulator prints under ``verbatim`` and compare to the AABB read straight
      from the PLY (scaled by ``ply_scale`` and the SI x1000, exactly as the loader
      does). No <voxels> block is present -- the box is auto-derived.
    * The b0 intra fraction equals the geometric volume fraction. Walkers are
      seeded UNIFORMLY over that AABB, so the fraction spawned inside the shell is
      mesh_volume / AABB_volume; the shell is IMPERMEABLE so each walker keeps its
      compartment, and with ``separate_signals`` the b0 (G=0) signal is just the
      walker count per compartment. For a CONVEX shell the CPU
      nearest-triangle-normal inside/outside test is reliable, so this is asserted
      on CPU. We compute mesh_volume / AABB_volume ourselves from the PLY.

(b) NON-CONVEX shell (dumbbell, ``bbox_concave.conf``).
    The CPU inside/outside test is nearest-triangle-normal, reliable only for
    convex shells; on a concave shell it can misclassify walkers near the reentrant
    waist, so the CPU b0 intra fraction may deviate from the true geometric value.
    The GPU uses a parity ray-cast (concave-safe) and is the TRUSTED classifier.
    So we (i) assert the concave case merely RUNS on CPU without crashing (and
    report the CPU fraction vs geometry), and (ii) add a GPU-parity check that runs
    CPU and GPU, asserts the GPU fraction matches geometry, and reports the CPU-GPU
    gap -- self-skipping cleanly when the binary has no CUDA / no GPU.

Runs as pytest (CPU + a GPU-parity test that self-skips) OR standalone:

  python3 tests/validation/test_bounding_box.py --gpu 0
"""
import argparse
import os
import re
import shutil
import sys
import tempfile
from collections import namedtuple

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))  # tests/
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "tools"))
from mcdc_testkit import io, paths, run, scheme  # noqa: E402
import make_meshes as mm  # noqa: E402  (tests/tools/make_meshes.py -- PLY reader + geometry)

import numpy as np  # noqa: E402

CONVEX_CONF = paths.accuracy("bbox_convex.conf")
CONCAVE_CONF = paths.accuracy("bbox_concave.conf")

# Tolerances. The voxel is the exact vertex AABB (the loader adds no margin), so a
# tight relative band captures "matches AABB (+small margin)". The intra fraction
# is a binomial estimate over N walkers (~0.8% 1-sigma at N=4000, p~0.5), so a few
# % band is comfortably > 3-sigma and robust across seeds/platforms.
VOXEL_RTOL = 0.02
FRAC_TOL = 0.04

_LIMIT_RE = r"{0}:\s*\(\s*([-0-9.eE+]+)\s*,\s*([-0-9.eE+]+)\s*,\s*([-0-9.eE+]+)\s*\)"

Run = namedtuple("Run", "stdout prefix skipped")


# --------------------------------------------------------------------------- #
#  Plumbing                                                                    #
# --------------------------------------------------------------------------- #
def _mesh_scale(conf_text):
    """Internal scale factor the loader applies to PLY vertices (file unit -> mm)."""
    ps = io.read_conf_value(conf_text, "ply_scale")
    scale = float(ps) if ps is not None else 1.0
    use_mm_ms = io.read_conf_value(conf_text, "use_mm_ms")
    si = not (use_mm_ms is not None and str(use_mm_ms).strip() in ("1", "true", "True"))
    return scale * (1000.0 if si else 1.0)


def _mesh_path(conf_text):
    """Absolute path to the PLY named on the conf's ``ply`` line."""
    rel = io.read_conf_value(conf_text, "ply")
    if rel is None:
        raise ValueError("conf has no 'ply' obstacle line")
    return os.path.join(paths.REPO_ROOT, rel)


def geometry(conf_text):
    """(aabb_min_mm, aabb_max_mm, volume_fraction) of the conf's mesh (from the PLY)."""
    verts, faces = mm.read_ply(_mesh_path(conf_text))
    lo, hi = mm.aabb(verts)
    scale = _mesh_scale(conf_text)
    return lo * scale, hi * scale, mm.volume_fraction(verts, faces)


def parse_limits(stdout):
    """(min xyz, max xyz) [internal mm] from the verbatim 'Min/Max limits' lines."""
    mn = re.search(_LIMIT_RE.format("Min limits"), stdout)
    mx = re.search(_LIMIT_RE.format("Max limits"), stdout)
    if not (mn and mx):
        return None, None
    return (np.array([float(x) for x in mn.groups()]),
            np.array([float(x) for x in mx.groups()]))


def run_bbox(binary, conf_text, out_dir, base, gpu=0, timeout=300):
    """Materialise the conf (exp_prefix -> out_dir/base, gpu flag), run, capture stdout.

    Returns a :class:`Run`; ``skipped`` is True iff the GPU path bailed (no CUDA).
    Raises on a real simulator error.
    """
    ov = {"exp_prefix": os.path.join(out_dir, base)}
    if gpu is not None:
        ov["gpu"] = int(gpu)
    conf_path = os.path.join(out_dir, base + ".conf")
    with open(conf_path, "w") as fh:
        fh.write(io.write_conf_override(conf_text, ov))
    res = run.run_sim(binary, conf_path, paths.REPO_ROOT, timeout=timeout)
    log = res.stdout or ""
    if gpu and run.is_gpu_skip(log):
        return Run(log, None, True)
    run.raise_on_error(res)
    return Run(log, os.path.join(out_dir, base), False)


def intra_fraction(prefix, b0_mask):
    """(b0 intra fraction, b0 total mean) from the separate intra/extra DWI files.

    At b0 (G=0), with default (infinite) T2, each walker contributes 1 to its
    compartment, so intra/(intra+extra) is the fraction of walkers classified
    inside -- the quantity that should equal mesh_volume / AABB_volume.
    """
    intra = np.atleast_1d(io.load_signal(prefix + "_DWI_intra.txt"))
    extra = np.atleast_1d(io.load_signal(prefix + "_DWI_extra.txt"))
    total = intra + extra
    b0 = np.asarray(b0_mask)
    return float(intra[b0].mean() / total[b0].mean()), float(total[b0].mean())


def _b0_mask(conf_text):
    sc = scheme.parse_scheme(os.path.join(paths.REPO_ROOT,
                                          io.read_conf_value(conf_text, "scheme_file")))
    return sc.b0_mask


# --------------------------------------------------------------------------- #
#  Measurements (shared by pytest + CLI)                                       #
# --------------------------------------------------------------------------- #
Convex = namedtuple("Convex", "vox_min vox_max exp_min exp_max frac geom_frac b0_total N")


def measure_convex(binary, gpu=0, timeout=300):
    conf_text = open(CONVEX_CONF).read()
    N = int(io.read_conf_value(conf_text, "N"))
    exp_min, exp_max, geom_frac = geometry(conf_text)
    work = tempfile.mkdtemp(prefix="mcdc_bbox_cvx_")
    try:
        r = run_bbox(binary, conf_text, work, "bbox_convex", gpu=gpu, timeout=timeout)
        if r.skipped:
            return None
        vmin, vmax = parse_limits(r.stdout)
        frac, b0_total = intra_fraction(r.prefix, _b0_mask(conf_text))
        return Convex(vmin, vmax, exp_min, exp_max, frac, geom_frac, b0_total, N)
    finally:
        shutil.rmtree(work, ignore_errors=True)


Concave = namedtuple("Concave", "frac geom_frac b0_total N skipped")


def measure_concave(binary, gpu=0, timeout=300):
    """Run the concave case; Concave(..., skipped) -- skipped True iff GPU bailed."""
    conf_text = open(CONCAVE_CONF).read()
    N = int(io.read_conf_value(conf_text, "N"))
    _, _, geom_frac = geometry(conf_text)
    work = tempfile.mkdtemp(prefix="mcdc_bbox_ccv_")
    try:
        r = run_bbox(binary, conf_text, work, "bbox_concave", gpu=gpu, timeout=timeout)
        if r.skipped:
            return Concave(None, geom_frac, None, N, True)
        frac, b0_total = intra_fraction(r.prefix, _b0_mask(conf_text))
        return Concave(frac, geom_frac, b0_total, N, False)
    finally:
        shutil.rmtree(work, ignore_errors=True)


# --------------------------------------------------------------------------- #
#  pytest entry points                                                         #
# --------------------------------------------------------------------------- #
def _binary_or_skip():
    import pytest
    binary = paths.binary_path()
    if not os.path.exists(binary):
        pytest.skip(f"simulator binary not built: {binary}")
    return binary


def test_bbox_convex_voxel_matches_aabb():
    """CPU: the auto-computed voxel equals the convex mesh AABB (no <voxels> block)."""
    c = measure_convex(_binary_or_skip(), gpu=0)
    assert c is not None and c.vox_min is not None, "no 'Min/Max limits' in output (need verbatim)"
    assert np.allclose(c.vox_min, c.exp_min, rtol=VOXEL_RTOL, atol=1e-6), \
        f"voxel min {c.vox_min} != mesh AABB min {c.exp_min}"
    assert np.allclose(c.vox_max, c.exp_max, rtol=VOXEL_RTOL, atol=1e-6), \
        f"voxel max {c.vox_max} != mesh AABB max {c.exp_max}"


def test_bbox_convex_intra_fraction():
    """CPU: b0 intra fraction equals the convex mesh volume/AABB fraction."""
    c = measure_convex(_binary_or_skip(), gpu=0)
    assert c is not None
    assert abs(c.b0_total - c.N) < 1.0, \
        f"b0 walker count {c.b0_total} != N {c.N} (intra+extra should cover every walker)"
    assert abs(c.frac - c.geom_frac) <= FRAC_TOL, \
        f"b0 intra fraction {c.frac:.4f} != geometric {c.geom_frac:.4f} (tol {FRAC_TOL})"


def test_bbox_concave_runs_cpu():
    """CPU: the NON-CONVEX case runs without crashing and classifies every walker.

    The CPU nearest-normal fraction may differ from the geometric value on a
    concave shell (that divergence is what the GPU-parity test guards); here we
    only require it to run and produce a sane, fully-accounted fraction.
    """
    c = measure_concave(_binary_or_skip(), gpu=0)
    assert not c.skipped and c.frac is not None, "concave CPU run produced no signal"
    assert abs(c.b0_total - c.N) < 1.0, f"b0 walker count {c.b0_total} != N {c.N}"
    assert 0.0 < c.frac < 1.0, f"nonsensical intra fraction {c.frac}"


def test_bbox_concave_gpu_parity():
    """GPU is the trusted concave classifier: assert GPU fraction ~= geometry.

    Runs the concave case on GPU (self-skips without CUDA) and on CPU, asserts the
    GPU (parity ray-cast) fraction matches the geometric volume fraction, and
    surfaces the CPU-vs-GPU gap for documentation.
    """
    import pytest
    binary = _binary_or_skip()
    g = measure_concave(binary, gpu=1)
    if g.skipped:
        pytest.skip("binary built without CUDA / no GPU available")
    c = measure_concave(binary, gpu=0)
    gap = abs((c.frac or 0.0) - g.frac)
    print(f"[concave parity] geom={g.geom_frac:.4f}  GPU={g.frac:.4f}  "
          f"CPU={c.frac:.4f}  |CPU-GPU|={gap:.4f}")
    assert abs(g.frac - g.geom_frac) <= FRAC_TOL, \
        f"GPU (trusted) intra fraction {g.frac:.4f} != geometric {g.geom_frac:.4f}"


# --------------------------------------------------------------------------- #
#  Standalone CLI (numpy only)                                                 #
# --------------------------------------------------------------------------- #
def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--bin", default=None)
    ap.add_argument("--gpu", type=int, default=0, choices=(0, 1),
                    help="also run the concave GPU-parity check (needs CUDA; self-skips)")
    a = ap.parse_args()

    binary = paths.binary_path(a.bin)
    if not os.path.exists(binary):
        print(f"FAIL: simulator binary not found: {binary}", file=sys.stderr)
        return 1

    ok = True
    c = measure_convex(binary, gpu=0)
    print("[bbox convex | CPU]")
    vok = c.vox_min is not None and np.allclose(c.vox_min, c.exp_min, rtol=VOXEL_RTOL, atol=1e-6) \
        and np.allclose(c.vox_max, c.exp_max, rtol=VOXEL_RTOL, atol=1e-6)
    fok = abs(c.frac - c.geom_frac) <= FRAC_TOL and abs(c.b0_total - c.N) < 1.0
    ok = ok and vok and fok
    print(f"  voxel   min={c.vox_min} max={c.vox_max}")
    print(f"  AABB    min={c.exp_min} max={c.exp_max}  -> {'OK' if vok else 'FAIL'}")
    print(f"  intra fraction={c.frac:.4f}  geometric={c.geom_frac:.4f}  "
          f"b0 walkers={c.b0_total:.0f}/{c.N}  -> {'OK' if fok else 'FAIL'}")

    cc = measure_concave(binary, gpu=0)
    print("[bbox concave | CPU]  (CPU nearest-normal may misclassify a concave shell)")
    ccok = (not cc.skipped) and (cc.frac is not None) and (0.0 < cc.frac < 1.0) \
        and abs(cc.b0_total - cc.N) < 1.0
    ok = ok and ccok
    print(f"  runs=OK  intra fraction={cc.frac:.4f}  geometric={cc.geom_frac:.4f}  "
          f"(CPU-geom gap={abs(cc.frac - cc.geom_frac):.4f})  "
          f"b0 walkers={cc.b0_total:.0f}/{cc.N}  -> {'OK' if ccok else 'FAIL'}")

    if a.gpu:
        g = measure_concave(binary, gpu=1)
        if g.skipped:
            print("[bbox concave | GPU parity] SKIP: binary built without CUDA / no GPU.")
        else:
            gok = abs(g.frac - g.geom_frac) <= FRAC_TOL
            ok = ok and gok
            print(f"[bbox concave | GPU parity] GPU (trusted)={g.frac:.4f}  "
                  f"geometric={g.geom_frac:.4f}  CPU={cc.frac:.4f}  "
                  f"|CPU-GPU|={abs(cc.frac - g.frac):.4f}  -> {'OK' if gok else 'FAIL'}")

    print("PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
